"""
Groundedness check -- Method 1: LLM-as-judge.

After the agent generates an answer, this module checks whether the answer
is actually supported by the retrieved context, rather than trusting every
answer equally.

Approach: LLM-as-judge. The judge model is given the retrieved context and
the generated answer, and asked to rate how well-supported the answer is,
plus flag any specific unsupported claims. Simple to run locally with
Ollama, easy to explain -- but it inherits the same model's blind spots
(see selfcheck.py for a second, independent method).

Usage (standalone test):
    python src/groundedness.py
"""

import json
import re
import ollama

LLM_MODEL = "qwen2.5:3b"

JUDGE_PROMPT = """You are a strict fact-checker. You are given a CONTEXT
(retrieved source passages) and an ANSWER generated by another AI. Your job
is to judge whether the ANSWER is fully supported by the CONTEXT.

Respond ONLY with a JSON object in this exact format:
{{
  "groundedness_score": <float between 0 and 1, where 1 = fully supported>,
  "unsupported_claims": [<list of specific phrases/claims in the answer that
    are NOT supported by the context, empty list if none>],
  "verdict": "<one of: 'grounded', 'partially grounded', 'not grounded'>"
}}

CONTEXT:
{context}

ANSWER:
{answer}

JSON:"""


def check_groundedness(context: str, answer: str) -> dict:
    prompt = JUDGE_PROMPT.format(context=context, answer=answer)
    response = ollama.generate(model=LLM_MODEL, prompt=prompt)
    raw = response["response"].strip()

    match = re.search(r"\{.*\}", raw, re.DOTALL)
    if not match:
        return {
            "groundedness_score": None,
            "unsupported_claims": [],
            "verdict": "unknown",
            "error": "Judge model did not return valid JSON",
        }

    try:
        result = json.loads(match.group(0))
        result.setdefault("groundedness_score", None)
        result.setdefault("unsupported_claims", [])
        result.setdefault("verdict", "unknown")
        return result
    except json.JSONDecodeError:
        return {
            "groundedness_score": None,
            "unsupported_claims": [],
            "verdict": "unknown",
            "error": "Could not parse judge output",
        }


if __name__ == "__main__":
    sample_context = "Apple reported total net sales of $383.3 billion for fiscal year 2023."
    sample_answer_good = "Apple's total net sales in fiscal 2023 were $383.3 billion."
    sample_answer_bad = "Apple's total net sales in fiscal 2023 were $500 billion, a record high."

    print("Testing grounded answer:")
    print(json.dumps(check_groundedness(sample_context, sample_answer_good), indent=2))

    print("\nTesting ungrounded answer:")
    print(json.dumps(check_groundedness(sample_context, sample_answer_bad), indent=2))
